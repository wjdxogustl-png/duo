// base 위에 over 를 덮어쓴다 (over 에 없는 키는 base 그대로)
export function mergeStrings(base, over) {
  if (!over) return base;
  const out = { ...base };
  for (const k of Object.keys(base)) {
    const b = base[k];
    const o = over[k];
    if (b && typeof b === "object") out[k] = mergeStrings(b, o && typeof o === "object" ? o : null);
    else if (typeof o === "string" && o.trim()) out[k] = o;
  }
  return out;
}

// 원본에는 있는데 번역에 빠진 키가 있는지
export function hasMissing(base, over) {
  if (!over) return true;
  return Object.keys(base).some((k) =>
    base[k] && typeof base[k] === "object" ? hasMissing(base[k], over[k]) : typeof over[k] !== "string"
  );
}
